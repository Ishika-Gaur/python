from collections import Counter

numbers = [1,2,3,4,5,6,7,7]

print(Counter(numbers))

sentence = "thinking about python"

print(Counter(sentence))

# Collections module Python ki Standard Library ka ek built-in module hai jo specialized container data types provide karta hai.
# Counter ek dictionary subclass hai jo kisi iterable ke elements kitni baar aaye hain, uska count store karta hai.